// ---------------------------------------------------------------------------
// Color utilities
// ---------------------------------------------------------------------------

const NAMED_COLORS: Record<string, string> = {
  black: '#000000', red: '#ff0000', green: '#008000', blue: '#0000ff',
  yellow: '#ffff00', cyan: '#00ffff', magenta: '#ff00ff', orange: '#ffa500',
  purple: '#800080', brown: '#a52a2a', gray: '#808080', grey: '#808080',
  pink: '#ffc0cb', lime: '#00ff00', navy: '#000080', teal: '#008080',
  maroon: '#800000', olive: '#808000', silver: '#c0c0c0',
};

/** Normalize any CSS color string to lowercase #rrggbb, or null for white/none. */
function normalizeHex(color: string): string | null {
  const c = color.trim().toLowerCase();
  if (!c || c === 'none' || c === 'transparent') return null;
  if (c === 'white' || c === '#fff' || c === '#ffffff') return null;
  if (c in NAMED_COLORS) {
    return NAMED_COLORS[c] === '#ffffff' ? null : NAMED_COLORS[c];
  }
  if (c.startsWith('#')) {
    if (c.length === 4) return '#' + c[1]+c[1]+c[2]+c[2]+c[3]+c[3];
    if (c.length === 7) return c;
    return null;
  }
  const rgb = c.match(/^rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)$/);
  if (rgb) {
    return '#' +
      parseInt(rgb[1]).toString(16).padStart(2, '0') +
      parseInt(rgb[2]).toString(16).padStart(2, '0') +
      parseInt(rgb[3]).toString(16).padStart(2, '0');
  }
  return null;
}

function isNearWhite(hex: string): boolean {
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return 0.299 * r + 0.587 * g + 0.114 * b > 220;
}

/** Inline-style fill (for SVG style="fill: ..."). */
function styleFill(el: Element): string | null {
  const m = (el.getAttribute('style') ?? '').match(/(?:^|;)\s*fill:\s*([^;]+)/i);
  return m ? m[1].trim() : null;
}

/**
 * Parse all <style> elements in the SVG and extract simple class→fill mappings.
 * Handles the common Illustrator/Inkscape pattern of `.clsName { fill: red; }`.
 *
 * Limitations: only single-class selectors are recognized — a rule like
 * `.a, .b { fill: red }` only attributes the fill to `.b`. ID selectors and
 * compound selectors are not handled. This covers the typical autogenerated
 * output; complex hand-authored CSS would need a real CSS parser.
 */
function parseClassFills(svgRoot: SVGSVGElement): Map<string, string> {
  const map = new Map<string, string>();
  svgRoot.querySelectorAll('style').forEach(styleEl => {
    const text = (styleEl.textContent ?? '').replace(/\/\*[\s\S]*?\*\//g, ''); // strip comments
    const ruleRegex = /\.([\w-]+)\s*\{([^}]*)\}/g;
    let m: RegExpExecArray | null;
    while ((m = ruleRegex.exec(text)) !== null) {
      const cls = m[1];
      const body = m[2];
      const fillMatch = body.match(/(?:^|[;{\s])fill\s*:\s*([^;}]+)/i);
      if (fillMatch) map.set(cls, fillMatch[1].trim());
    }
  });
  return map;
}

/**
 * Resolve the effective fill color for an SVG element, walking up ancestors.
 * Order matches CSS specificity: inline style > class rule > fill attribute.
 */
function resolveFill(el: Element, classFills: Map<string, string>): string | null {
  let cur: Element | null = el;
  while (cur) {
    // 1. Inline style="fill:..." (highest specificity)
    const styled = styleFill(cur);
    if (styled) return styled;
    // 2. CSS class rule from <style> in <defs>
    const classAttr = cur.getAttribute('class');
    if (classAttr) {
      for (const c of classAttr.split(/\s+/)) {
        const f = classFills.get(c);
        if (f) return f;
      }
    }
    // 3. fill="..." presentation attribute (lowest CSS specificity)
    const direct = cur.getAttribute('fill');
    if (direct) return direct;
    cur = cur.parentElement;
  }
  return null;
}

// ---------------------------------------------------------------------------
// SVG → per-layer split
// ---------------------------------------------------------------------------

/** Collect leaf renderable elements (those that produce visible geometry). */
const RENDERABLE_TAGS = new Set([
  'path', 'rect', 'circle', 'ellipse', 'polygon', 'polyline', 'line',
]);

/**
 * Strip any `fill: ...` declaration from a CSS style string. We re-apply fill
 * explicitly via an attribute so the cloned leaf doesn't carry a fill that
 * came from an ancestor we're not re-emitting.
 */
function stripFillFromStyle(style: string): string {
  return style
    .split(';')
    .map(s => s.trim())
    .filter(s => s && !/^fill\s*:/i.test(s))
    .join('; ');
}

function splitSvgIntoLayers(svgRoot: SVGSVGElement): { layers: Layer[]; order: string[] } {
  const classFills = parseClassFills(svgRoot);
  const buckets = new Map<string, string[]>();
  const order: string[] = [];

  svgRoot.querySelectorAll('*').forEach(el => {
    if (!RENDERABLE_TAGS.has(el.tagName.toLowerCase())) return;
    const raw = resolveFill(el, classFills);
    if (!raw) return;
    const hex = normalizeHex(raw);
    if (!hex || isNearWhite(hex)) return;

    if (!buckets.has(hex)) {
      buckets.set(hex, []);
      order.push(hex);
    }

    // Clone and force the fill explicitly. We may emit this leaf without its
    // original ancestor chain, so any inherited fill must be baked in here.
    const clone = el.cloneNode(true) as Element;
    const inlineStyle = clone.getAttribute('style');
    if (inlineStyle) {
      const cleaned = stripFillFromStyle(inlineStyle);
      if (cleaned) clone.setAttribute('style', cleaned);
      else clone.removeAttribute('style');
    }
    clone.setAttribute('fill', hex);

    // Collect ancestor transforms (outermost → innermost) so the leaf renders
    // in the same coordinate system as in the original SVG. Authors commonly
    // wrap content in <g transform="matrix(...)"> (Inkscape layer transforms,
    // Illustrator artboard transforms, etc.) — losing these rotates/scales
    // /translates the entire piece.
    const ancestorTransforms: string[] = [];
    let cur: Element | null = el.parentElement;
    while (cur && cur !== svgRoot) {
      const t = cur.getAttribute('transform');
      if (t) ancestorTransforms.unshift(t);
      cur = cur.parentElement;
    }

    let html = clone.outerHTML;
    for (let i = ancestorTransforms.length - 1; i >= 0; i--) {
      html = `<g transform="${ancestorTransforms[i]}">${html}</g>`;
    }
    buckets.get(hex)!.push(html);
  });

  const layers: Layer[] = order.map(colorHex => ({
    colorHex,
    svgFragment: buckets.get(colorHex)!.join('\n'),
  }));

  return { layers, order };
}

